--
-- 그래서 만들기 전에 물어본다. 막지는 않는다 — 다시 만들 이유는 사용자에게 있을 수 있고
-- (난이도를 바꾸고 싶다, 지난번이 마음에 안 들었다) 그건 우리가 판단할 일이 아니다.

-- 정규화한 주제로 찾는다. 공백만 다른 것을 다른 주제로 보면 이 기능이 하는 일이 없다.
create index if not exists worksheets_user_topic_idx
  on public.worksheets (user_id, lower(regexp_replace(btrim(topic), '\s+', ' ', 'g')))
  where status = 'ready';
